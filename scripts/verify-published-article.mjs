import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
const sitemap = await readFile('dist/sitemap.xml', 'utf8');
const archive = await readFile('dist/articles/index.html', 'utf8');
const slug = 'crm-upload-check-20261001';
assert.ok(!sitemap.includes(slug));
assert.ok(!archive.includes(slug));
assert.equal(await access('dist/articles/' + slug + '/index.html').then(() => true, () => false), false);
assert.ok(sitemap.includes('https://pxlgrid.design/articles/why-business-needs-website/'));
console.log('PASS: existing public article included; retired test absent from artifact, archive and sitemap.');
