import { chromium } from 'playwright-core';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { portfolioFixtures } from '../src/portfolio-data.ts';
import { validatePortfolioPayload } from '../supabase/functions/_shared/portfolio.ts';

const base = process.env.PIXEL_TEST_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch({ executablePath: process.env.PIXEL_BROWSER_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const report = { viewports: [], errors: [], violations: [], checks: [], requestsAfterSubmit: [] };
await mkdir('outputs', { recursive: true });
try {
  const fixture = portfolioFixtures.find(item => item.payload.link === '/portfolio/gorgan-khaneh/');
  assert.ok(fixture);
  assert.equal(fixture.kind, 'concept');
  assert.equal(validatePortfolioPayload(fixture.payload, 'concept', '00000000-0000-0000-0000-000000000001', fixture.id).theme, 'estate');
  assert.doesNotMatch(await readFile('dist/sitemap.xml', 'utf8'), /\/portfolio\/gorgan-khaneh/);
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', error => report.errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') report.errors.push(message.text()); });
  await page.goto(`${base}/portfolio/gorgan-khaneh/`);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => !document.querySelector('.gk-search-fields').disabled);
  assert.equal(await page.locator('h1').count(), 1);
  assert.match(await page.title(), /املاک گرگان‌خانه/);
  assert.equal(await page.locator('meta[name="robots"]').getAttribute('content'), 'noindex, nofollow');
  assert.ok(await page.getByText('کانسپت نمایشی پیکسل؛ دفتر املاک واقعی نیست', { exact: true }).isVisible());
  assert.equal(await page.locator('.gk-property').count(), 6);
  assert.equal(await page.locator('.gk-district').count(), 6);
  for (const img of await page.locator('.gorgan-khaneh-page img').all()) {
    await img.scrollIntoViewIfNeeded();
    await img.evaluate(element => element.decode());
    assert.ok(await img.evaluate(element => element.naturalWidth > 0));
  }
  for (const width of [360, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.evaluate(() => window.scrollTo(0, 0));
    const layout = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }));
    assert.ok(layout.scrollWidth <= width, `Horizontal overflow at ${width}`);
    report.viewports.push(layout);
    await page.screenshot({ path: `outputs/gorgan-khaneh-${width}.png`, fullPage: true });
    await page.screenshot({ path: `outputs/gorgan-khaneh-hero-${width}.png` });
    if (width === 390 || width === 1440) {
      const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
      report.violations.push(...audit.violations.map(({ id, nodes }) => ({ width, id, nodes: nodes.map(({ target, failureSummary }) => ({ target, failureSummary })) })));
    }
  }
  const links = await page.locator('a[href^="#"]').evaluateAll(links => [...new Set(links.map(link => link.getAttribute('href')))]);
  for (const link of links) assert.equal(await page.locator(link).count(), 1, `Missing anchor ${link}`);
  assert.deepEqual(await page.locator('a:not([href^="#"])').evaluateAll(links => [...new Set(links.map(link => link.getAttribute('href')))]), ['/portfolio/']);
  const search = page.getByRole('button', { name: 'جستجوی ملک', exact: true });
  const reset = page.getByRole('button', { name: 'پاک‌کردن فیلترها' });
  await page.locator('#gk-transaction').selectOption('rent');
  await search.click();
  assert.equal(await page.locator('.gk-property').count(), 2);
  await page.locator('#gk-type').selectOption('apartment');
  await page.locator('#gk-district').selectOption('عدالت');
  await page.locator('#gk-minimum').fill('۶۰۰');
  await page.locator('#gk-maximum').fill('۸۰۰');
  await search.click();
  assert.equal(await page.locator('.gk-property').count(), 1);
  assert.equal(await page.locator('.gk-property').getAttribute('id'), 'property-GK-102');
  assert.match(await page.locator('.gk-property-price').textContent(), /۱۶ میلیون تومان/);
  await reset.click();
  assert.equal(await page.locator('.gk-property').count(), 6);
  await page.locator('#gk-transaction').selectOption('sale');
  await page.locator('#gk-type').selectOption('apartment');
  await page.locator('#gk-minimum').fill('۱۰٬۰۰۰');
  await page.locator('#gk-maximum').fill('۲۰٬۰۰۰');
  await search.click();
  assert.equal(await page.locator('.gk-property').count(), 2);
  await page.locator('#gk-maximum').fill('۵۰۰۰');
  await search.click();
  assert.match(await page.getByRole('alert').textContent(), /حداکثر قیمت/);
  await page.locator('#gk-minimum').fill('abc');
  await search.click();
  assert.match(await page.getByRole('alert').textContent(), /عدد فارسی یا انگلیسی/);
  await reset.click();
  await page.locator('#gk-type').selectOption('land');
  await page.locator('#gk-transaction').selectOption('rent');
  await search.click();
  assert.equal(await page.locator('.gk-property').count(), 0);
  await page.getByRole('button', { name: 'نمایش همهٔ فایل‌ها' }).click();
  assert.equal(await page.locator('.gk-property').count(), 6);
  await page.getByRole('link', { name: 'مشاهده فایل‌های نمونهٔ زیارت' }).click();
  assert.equal(await page.locator('.gk-property').getAttribute('id'), 'property-GK-103');
  assert.equal(await page.locator('#gk-district').inputValue(), 'زیارت');
  await page.locator('.gk-property-details summary').click();
  assert.ok(await page.locator('.gk-detail-content').isVisible());
  await page.getByRole('link', { name: 'پرس‌وجو دربارهٔ این فایل' }).click();
  assert.equal(new URL(page.url()).hash, '#consultation');
  assert.match(await page.locator('.gk-interest').textContent(), /ویلای مدرن در زیارت/);
  report.checks.push('Transaction, type, district, Persian budgets, purchase/deposit filtering, validation, empty state, reset and district shortcuts');
  report.checks.push('Inline property details and contextual consultation on the same route');
  await page.setViewportSize({ width: 390, height: 844 });
  const toggle = page.locator('.gk-mobile-menu summary');
  await toggle.click();
  assert.ok(await page.getByRole('navigation', { name: 'ناوبری موبایل' }).isVisible());
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.gk-mobile-menu').getAttribute('open'), null);
  await toggle.click();
  await page.getByRole('navigation', { name: 'ناوبری موبایل' }).getByRole('link', { name: 'محله‌های گرگان' }).click();
  assert.equal(new URL(page.url()).hash, '#districts');
  assert.equal(await page.locator('.gk-mobile-menu').getAttribute('open'), null);
  const submit = page.getByRole('button', { name: 'امتحان درخواست مشاوره' });
  await submit.click();
  assert.equal(await page.locator('#gk-name').evaluate(element => element.validity.valueMissing), true);
  await page.locator('#gk-name').fill('بازدیدکنندهٔ نمونه');
  await page.locator('#gk-phone').fill('123');
  await submit.click();
  assert.equal(await page.locator('#gk-phone').evaluate(element => element.validity.patternMismatch), true);
  await page.locator('#gk-phone').fill('۰۹۱۲۳۴۵۶۷۸۹');
  await page.locator('#gk-need').fill('یک آپارتمان دوخوابه برای اجاره در محدودهٔ عدالت');
  await page.waitForLoadState('networkidle');
  page.on('request', request => report.requestsAfterSubmit.push(request.url()));
  await submit.click();
  assert.equal(await page.locator('.gk-form-status').textContent(), 'این نسخه نمایشی است؛ درخواستی ثبت نشد.');
  assert.equal(await page.locator('#gk-phone').inputValue(), '');
  assert.deepEqual(report.requestsAfterSubmit, []);
  assert.deepEqual(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length })), { local: 0, session: 0 });
  report.checks.push('Mobile menu, Escape, anchors, required fields, phone validation, no form requests or storage');
  await page.getByRole('button', { name: 'اینستاگرام · نمایشی' }).click();
  assert.match(await page.locator('.gk-footer-social [role="status"]').textContent(), /وجود ندارد/);
  const noJs = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
  const staticPage = await noJs.newPage();
  await staticPage.goto(`${base}/portfolio/gorgan-khaneh/`);
  assert.ok(await staticPage.locator('h1').isVisible());
  assert.equal(await staticPage.locator('.gk-property').count(), 6);
  assert.ok(await staticPage.locator('#gk-name').isDisabled());
  assert.ok(await staticPage.locator('#gk-transaction').isDisabled());
  await staticPage.locator('.gk-property-details summary').first().click();
  assert.ok(await staticPage.locator('.gk-detail-content').first().isVisible());
  await staticPage.goto(`${base}/portfolio/`);
  assert.ok(await staticPage.getByRole('heading', { name: /گرگان‌خانه/ }).isVisible());
  await noJs.close();
  report.checks.push('Prerendered landing and portfolio, native inline details and safe disabled forms without JavaScript');
  await writeFile('outputs/gorgan-khaneh-verification.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
  assert.deepEqual(report.errors, []);
  assert.deepEqual(report.violations, []);
} finally { await browser.close(); }
